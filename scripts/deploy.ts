import { artifacts, network } from "hardhat";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const GENERATED_FILE_PATH = path.join(
  process.cwd(),
  "src",
  "lib",
  "generated",
  "receiptuary.generated.ts",
);

async function syncFrontendContractConfig(address: string) {
  const artifact = await artifacts.readArtifact("Receiptuary");
  const networkName = process.env.HARDHAT_NETWORK || network.name || "hardhat";
  const generatedSource = `/* AUTO-GENERATED by scripts/deploy.ts */\n\nexport const DEPLOYED_NETWORK = "${networkName}";\nexport const DEPLOYED_CONTRACT_ADDRESS = "${address}" as const;\n\nexport const DEPLOYED_RECEIPTUARY_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;

  await mkdir(path.dirname(GENERATED_FILE_PATH), { recursive: true });
  await writeFile(GENERATED_FILE_PATH, generatedSource, "utf8");
}

async function main() {
  const { ethers } = await network.create();
  const contract = await ethers.deployContract("Receiptuary");
  await contract.waitForDeployment();

  const deployedAddress = await contract.getAddress();
  await syncFrontendContractConfig(deployedAddress);

  console.log("Receiptuary deployed:", deployedAddress);
  console.log("Synced frontend config:", GENERATED_FILE_PATH);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
